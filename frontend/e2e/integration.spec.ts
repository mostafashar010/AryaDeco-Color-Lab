test('real server loads the Persian lab with no missing resources or console exceptions', async ({ page }) => {
  const errors: string[] = []
  const failed: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('response', response => {
    if (response.status() >= 400 && response.url().startsWith(process.env.COLORLAB_TEST_ORIGIN ?? 'http://localhost:8443')) failed.push(`${response.status()} ${response.url()}`)
  })
  const response = await page.goto('/')
  expect(response?.status()).toBe(200)
  await expect(page.getByText('AryaDeco', { exact: false }).first()).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'fa')
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }))
  expect(dimensions.document).toBeLessThanOrEqual(dimensions.viewport + 1)
  expect(errors).toEqual([])
  expect(failed).toEqual([])
})

