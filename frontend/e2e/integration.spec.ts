  const response = await measurementResponse
  expect(response.status()).toBe(200)
  const measurement = await response.json()
  expect(measurement.approved).toBe(false)
  expect(measurement.independentValidationStatus).toBe('notTested')
  expect(measurement.displayDriveRgb).toBeNull()
  expect(measurement.sourceFrameProvenance.length).toBeGreaterThanOrEqual(10)
  expect(measurement.sourceFrameProvenance[0].mediaTime).toBeGreaterThanOrEqual(0)
  expect(measurement.sourceFrameProvenance[0].presentedFrames).toBeGreaterThanOrEqual(0)
  // Fake Chrome video is a synthetic API path test, not evidence of physical color.
  await expect(page.getByRole('table').locator('tbody tr')).toHaveCount(1)
