  await page.getByLabel('تصویر اصلی برای بازپخش').setInputFiles(path.resolve('../references/02-swatch-bands.jpg'))
  const preview = page.getByAltText('پیش‌نمایش canonical تصویر اصلی')
  await expect(preview).toBeVisible()
  await expect(page.getByText('منبع: display-p3.', { exact: false })).toBeVisible()
  const plane = page.getByLabel('ویرایش ناحیه در مختصات اصلی')
  await plane.scrollIntoViewIfNeeded()
  let box = await plane.boundingBox()
  if (!box) throw new Error('Original-coordinate image plane unavailable')
  await page.evaluate(y=>window.scrollBy(0,y),box.y+box.height*.18-150)
  box=await plane.boundingBox()
  if(!box)throw new Error('Scrolled image plane unavailable')
  await page.mouse.move(box.x + box.width * 0.30, box.y + box.height * 0.18)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.70, box.y + box.height * 0.24, { steps: 5 })
  await page.mouse.up()
